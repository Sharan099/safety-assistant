"""Build `evals/datasets/regulatory_variations_v1.yaml`: deterministic phrasing variants of the
human-written answerable cases — scoped ("In UN R94, …"), imperative ("State …"), keyword/short
form, and a typo variant — each inheriting the parent's ground truth and marked `source: synthetic`.
The point is breadth of phrasing on known truth, not new facts.

    uv run python scripts/eval/build_variations.py
"""

from __future__ import annotations

import pathlib
import re
import sys

import yaml

from safety_assistant.evaluation.dataset import load_dataset
from safety_assistant.retrieval.filters import significant_tokens

SRC = pathlib.Path("evals/datasets/regulatory_v2.yaml")
OUT = pathlib.Path("evals/datasets/regulatory_variations_v1.yaml")
_TYPO = {
    "regulation": "regulaton",
    "requirement": "requirment",
    "maximum": "maxium",
    "vehicle": "vehcile",
    "criterion": "criteron",
}


def _reg_label(key: str) -> str:
    return key.replace("UN-R", "UN R").replace("-", " ")


def _short(query: str) -> str | None:
    words = [
        w
        for w in re.findall(r"[A-Za-z0-9*_.\-]+", query)
        if w.lower() in significant_tokens(query) or re.search(r"\d", w)
    ]
    # fewer than three content words is not a question an engineer would type ("out")
    return " ".join(words[:6]) if len(words) >= 3 else None


def _typo(query: str) -> str | None:
    for src, bad in _TYPO.items():
        if src in query.lower():
            return re.sub(src, bad, query, count=1, flags=re.IGNORECASE)
    return None


def main() -> int:
    ds = load_dataset(SRC, source="human")
    out = []
    for c in ds.cases:
        if c.answerability != "answerable" or not c.regulation_keys or c.query_type == "adversarial_injection":
            continue
        base = c.model_dump(mode="json", exclude_none=True)
        base.update(source="synthetic", human_reviewed=False, review_status="DRAFT")
        for k in ("reviewer_notes",):
            base.pop(k, None)
        reg = sorted(c.regulation_keys)[0]
        variants = {
            "scoped": f"In {_reg_label(reg)}, {c.query[0].lower() + c.query[1:]}"
            if not c.query.lower().startswith("in un")
            else None,
            "imperative": f"State the exact requirement: {c.query.rstrip('?')}.",
            "short": _short(c.query),
            "typo": _typo(c.query),
        }
        for kind, q in variants.items():
            if not q or q.strip().lower() == c.query.strip().lower():
                continue
            v = dict(base)
            v.update(
                case_id=f"{c.case_id}-{kind}",
                query=q,
                query_type=f"variation_{kind}",
                notes=f"phrasing variant ({kind}) of {c.case_id}; same truth",
            )
            out.append(v)
    OUT.write_text(
        "# Phrasing variants of the human-written answerable cases of regulatory_v2 (same ground truth).\n"
        "# Generated by scripts/eval/build_variations.py; source=synthetic, not human-reviewed.\n"
        + yaml.safe_dump(
            {"dataset_version": "regulatory_variations_v1", "cases": out},
            sort_keys=False,
            allow_unicode=True,
            width=120,
        ),
        encoding="utf-8",
    )
    print(f"{len(out)} variants → {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
